import path from "node:path";
import { readFileSync } from "node:fs";
import { zipSync } from "fflate";
import { test, expect } from "@playwright/test";
import { loginViaApi } from "./support/auth";
import { resetE2eDatabase } from "./support/reset-db";
const fixture = path.join(__dirname, "fixtures/revierkarte-roundtrip.kml");
test.beforeEach(async () => { await resetE2eDatabase(); });
test("KML importieren, alle Ringe speichern, wiederöffnen, exportieren und geschützt ergänzen", async ({ page }, testInfo) => {
  await loginViaApi(page, "revier-admin");
  await page.goto("/app/revierkarte");
  await expect(page.getByLabel("KML/KMZ importieren")).toBeEnabled();
  await page.getByLabel("KML/KMZ importieren").setInputFiles({name: "test.kmz", mimeType: "application/vnd.google-earth.kmz", buffer: Buffer.from(zipSync({"doc.kml": readFileSync(fixture)}))});
  await expect(page.getByText("2 Flächen · 3 Teilflächen · 1 innere Ringe.", {exact:false})).toBeVisible();
  expect((await (await page.request.get('/api/v1/revier-map')).json()).map).toBeNull();
  await page.getByRole("button", {name:"Als Entwurf übernehmen"}).click();
  await expect(page.getByLabel("Teilfläche oder Ring").locator('option')).toHaveCount(4);
  await page.getByRole("button", {name:"Reviergrenze speichern",exact:true}).click();
  await expect(page.getByRole("status")).toContainText("Reviergrenze gespeichert");
  const saved = await (await page.request.get('/api/v1/revier-map')).json();
  expect(saved.map.areas[0].polygons).toHaveLength(2);
  expect(saved.map.areas[0].polygons[0]).toHaveLength(2);
  expect(saved.map.areas[1].kind).toBe('exclusion');
  await page.reload();
  await expect(page.getByLabel("Teilfläche oder Ring").locator('option')).toHaveCount(4);
  await page.getByLabel("Teilfläche oder Ring").selectOption('0:0:1');
  await expect(page.getByText('4 Punkte im gewählten Ring', {exact:false})).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('austausch-gespeichert.png'),fullPage:true});
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', {name:'Gespeicherte Karte als KML exportieren'}).click();
  const download = await downloadPromise;
  const downloaded = testInfo.outputPath('hege-revierkarte.kml');
  await download.saveAs(downloaded);
  await page.getByLabel("KML/KMZ importieren").setInputFiles(downloaded);
  await expect(page.getByLabel("Übernahme")).toHaveValue('append');
  await page.getByRole("button", {name:"Als Entwurf übernehmen"}).click();
  expect((await (await page.request.get('/api/v1/revier-map')).json()).map).toEqual(saved.map);
  await expect(page.getByRole("button", {name:"Reviergrenze speichern",exact:true})).toBeDisabled();
  await page.getByRole('button',{name:'Rückgängig',exact:true}).click();
  await expect(page.getByLabel("Teilfläche oder Ring").locator('option')).toHaveCount(4);
  await page.getByLabel("KML/KMZ importieren").setInputFiles(downloaded);
  await page.getByLabel("Übernahme").selectOption('replace');
  await page.getByRole("button", {name:"Als Entwurf übernehmen"}).click();
  // Ein unveränderter Rundlauf muss nicht nochmals gespeichert werden.
  await expect(page.getByLabel("Teilfläche oder Ring").locator('option')).toHaveCount(4);
  await page.getByLabel("KML/KMZ importieren").setInputFiles(path.join(__dirname, "fixtures/revierkarte-mymaps-return.kml"));
  await expect(page.getByText("2 Flächen · 3 Teilflächen · 1 innere Ringe.", {exact:false})).toBeVisible();
  await page.getByLabel("Übernahme").selectOption('replace');
  await page.getByRole("button", {name:"Als Entwurf übernehmen"}).click();
  await page.getByLabel("Bestehende Reviergrenze bewusst ändern").check();
  await page.getByRole("button", {name:"Reviergrenze speichern",exact:true}).click();
  await expect(page.getByRole("status")).toContainText("Reviergrenze gespeichert");
  const returned = (await (await page.request.get('/api/v1/revier-map')).json()).map;
  expect(returned.areas.map((a: {kind: string}) => a.kind)).toEqual(saved.map.areas.map((a: {kind: string}) => a.kind));
  const originalNumbers = saved.map.areas.flatMap((a: {polygons: number[][][][]}) => a.polygons.flat(3));
  const returnedNumbers = returned.areas.flatMap((a: {polygons: number[][][][]}) => a.polygons.flat(3));
  expect(returnedNumbers).toHaveLength(originalNumbers.length);
  returnedNumbers.forEach((n: number, i: number) => expect(n).toBeCloseTo(originalNumbers[i], 12));
  await page.getByLabel("KML/KMZ importieren").setInputFiles({name:'kaputt.kml',mimeType:'application/xml',buffer:Buffer.from('<kml>kaputt')});
  await expect(page.getByTestId('boundary-editor').getByRole('alert')).toContainText('Ungültige KML-Datei');
  expect((await (await page.request.get('/api/v1/revier-map')).json()).map).toEqual(returned);
  await page.getByText('Anleitung: Google My Maps ↔ hege',{exact:true}).click();
  await expect(page.getByRole('heading',{name:'Von hege nach Google My Maps'})).toBeVisible();
  await loginViaApi(page, 'ausgeher');
  await page.goto('/app/revierkarte');
  await expect(page.getByLabel("KML/KMZ importieren")).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Gespeicherte Karte als KML exportieren'})).toBeVisible();
});
